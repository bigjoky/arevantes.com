import assert from 'node:assert/strict';
import { Buffer } from 'node:buffer';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const source = await readFile(new URL('../../resources/js/components/quotes/types.ts', import.meta.url), 'utf8');
const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } });
const { quoteUrl, quoteDate, quoteMoney } = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
const filters = { search: 'García & Sol', status: 'sent', page: '3', sort: 'amount', direction: 'desc', customer: '42', view: 'table', tab: 'workflow', empty: '' };
const detail = new URL(quoteUrl(filters, 7, 'versions'), 'https://example.test');
assert.equal(detail.pathname, '/quotes/7');
assert.equal(detail.searchParams.get('search'), 'García & Sol');
assert.equal(detail.searchParams.get('page'), '3');
assert.equal(detail.searchParams.get('tab'), 'versions');
assert.equal(detail.searchParams.get('customer'), '42');
assert.equal(detail.searchParams.get('empty'), null);
const back = new URL(quoteUrl(filters), 'https://example.test');
assert.equal(back.pathname, '/quotes');
assert.equal(back.searchParams.get('tab'), null);
assert.equal(back.searchParams.get('status'), 'sent');
assert.equal(back.searchParams.get('sort'), 'amount');
assert.equal(back.searchParams.get('direction'), 'desc');
assert.equal(back.searchParams.get('view'), 'table');
assert.equal(new URL(quoteUrl(filters, 7, 'summary'), 'https://example.test').searchParams.get('tab'), null);
assert.equal(quoteDate(null), '—');
assert.equal(quoteDate('2026-09-28'), '28/09/2026');
assert.match(quoteMoney('37200.00'), /37\.200,00/);
console.log('16 quote navigation and presentation assertions passed');
