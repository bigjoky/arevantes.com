export function useLocale() {
    const locale = useMemo<Locale>(() => {
        if (typeof navigator === 'undefined') {
            return 'en';
        }

        return navigator.language.toLowerCase().startsWith('es') ? 'es' : 'en';
    }, []);

    return {
        locale,
        t: dictionaries[locale],
    };
}
